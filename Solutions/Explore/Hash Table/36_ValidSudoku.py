def sol(board):
    # rows
    for i in range(9):
        sett = set()
        for j in range(9):
            curr = board[i][j]
            if curr in sett:
                return False
            elif curr != '.':
                sett.add(curr)

    # columns
    for i in range(9):
        sett = set()
        for j in range(9):
            curr = board[j][i]
            if curr in sett:
                return False
            elif curr != '.':
                sett.add(curr)

    # boxes
    pos = [(0, 0), (0, 3), (0, 6), (3, 0), (3, 3), (3, 6), (6, 0), (6, 3), (6, 6)]

    for i, j in pos:
        sett = set()
        for row in range(i, i+3):
            for col in range(j, j+3):
                curr = board[row][col]
                if curr in sett:
                    return False
                elif curr != '.':
                    sett.add(curr)

    return True

